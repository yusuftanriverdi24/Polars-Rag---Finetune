TokenCounter = Callable[[str], int]


@dataclass
class Chunk:
    id: str
    kind: str  # "api" | "guide"
    source: str
    title: str
    section: str
    api_names: list[str]
    text: str
    n_tokens: int = 0
    signature: str = ""
    part: int = 0
    n_parts: int = 1
    extra: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict) -> "Chunk":
        return cls(**d)


