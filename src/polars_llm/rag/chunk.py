def build_chunks(corpus: Path = CORPUS_DIR, count: TokenCounter | None = None) -> tuple[list[Chunk], dict]:
    count = count or load_token_counter()
    api_chunks, rst_pages, unresolved = build_api_chunks(corpus, count)
    known = {n for c in api_chunks for n in c.api_names}
    guide_chunks = build_guide_chunks(corpus, count, known, rst_pages)
    chunks = api_chunks + guide_chunks
    ids = [c.id for c in chunks]
    if len(ids) != len(set(ids)):
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        raise ValueError(f"duplicate chunk ids: {dupes[:10]}")
    return chunks, {"unresolved_api_entries": unresolved}


def _distribution(values: list[int]) -> dict:
    if not values:
        return {}
    qs = statistics.quantiles(values, n=20, method="inclusive") if len(values) > 1 else [values[0]] * 19
    return {
        "count": len(values),
        "total_tokens": sum(values),
        "mean": round(statistics.fmean(values), 1),
        "min": min(values),
        "p10": round(qs[1]),
        "p25": round(qs[4]),
        "median": round(statistics.median(values)),
        "p75": round(qs[14]),
        "p90": round(qs[17]),
        "p95": round(qs[18]),
        "max": max(values),
    }


def chunk_stats(chunks: list[Chunk]) -> dict:
    by_kind: dict[str, list[int]] = {}
    for c in chunks:
        by_kind.setdefault(c.kind, []).append(c.n_tokens)
    return {
        "n_chunks": len(chunks),
        "tokens_all": _distribution([c.n_tokens for c in chunks]),
        "tokens_by_kind": {k: _distribution(v) for k, v in sorted(by_kind.items())},
        "n_api_names_documented": len({n for c in chunks if c.kind == "api" for n in c.api_names}),
        "n_api_pages_split": len({c.api_names[0] for c in chunks if c.kind == "api" and c.n_parts > 1}),
        "n_guide_chunks_with_api_names": sum(1 for c in chunks if c.kind == "guide" and c.api_names),
    }


def write_chunks(chunks: list[Chunk], path: Path) -> str:
    """Write chunks as JSONL (stable order) and return the file's sha256."""

    path.parent.mkdir(parents=True, exist_ok=True)
    data = "".join(json.dumps(c.to_dict(), ensure_ascii=False, sort_keys=True) + "\n" for c in chunks)
    path.write_text(data, encoding="utf-8", newline="\n")
    return hashlib.sha256(data.encode("utf-8")).hexdigest()


def read_chunks(path: Path = DEFAULT_OUT) -> list[Chunk]:
    with path.open(encoding="utf-8") as fh:
        return [Chunk.from_dict(json.loads(line)) for line in fh if line.strip()]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Chunk the Polars docs corpus.")
    parser.add_argument("--corpus", default=str(CORPUS_DIR))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--stats", default=str(DEFAULT_STATS))
    args = parser.parse_args(argv)

    import polars as pl

    chunks, info = build_chunks(Path(args.corpus))
    sha = write_chunks(chunks, Path(args.out))
    stats = {
        "polars_version": pl.__version__,
        "tokenizer": f"{TOKENIZER_ID}@{TOKENIZER_REVISION}",
        "chunks_sha256": sha,
        "params": {
            "api_split_tokens": API_SPLIT_TOKENS,
            "api_part_tokens": API_PART_TOKENS,
            "guide_min_tokens": GUIDE_MIN_TOKENS,
            "guide_max_tokens": GUIDE_MAX_TOKENS,
        },
        **chunk_stats(chunks),
        "unresolved_api_entries": info["unresolved_api_entries"],
    }
    stats_path = Path(args.stats)
    stats_path.parent.mkdir(parents=True, exist_ok=True)
    stats_path.write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")

    print(f"Wrote {len(chunks)} chunks to {args.out} (sha256 {sha[:12]})")
    for kind, d in stats["tokens_by_kind"].items():
        print(f"  {kind:<6} n={d['count']:<5} tokens: min {d['min']} p25 {d['p25']} median {d['median']} "
              f"p75 {d['p75']} p95 {d['p95']} max {d['max']} (mean {d['mean']})")
    d = stats["tokens_all"]
    print(f"  all    n={d['count']:<5} tokens: min {d['min']} median {d['median']} p95 {d['p95']} max {d['max']}")
    print(f"  API names documented: {stats['n_api_names_documented']}; API pages split: {stats['n_api_pages_split']}")
    if info["unresolved_api_entries"]:
        print(f"  unresolved reference entries: {len(info['unresolved_api_entries'])} (see {args.stats})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
