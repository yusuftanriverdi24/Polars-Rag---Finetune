API_SPLIT_TOKENS = 1000  # split an API page only above this
API_PART_TOKENS = 700  # target size of each part when splitting
GUIDE_MIN_TOKENS = 300
GUIDE_MAX_TOKENS = 500

REFERENCE_DIR = "py-polars/docs/source/reference"
