"""Chunk the pinned Polars 2.0.0 docs corpus (``data/raw``) for retrieval.

Two kinds of chunks:

``api``   One chunk per documented Python API object (function / method /
          property / class), i.e. one per page of the rendered API reference.
          The reference ``.rst`` files under ``py-polars/docs/source/reference``
          are Sphinx *autosummary stubs*: they list which objects are documented
          (and under which page title / section), while the page content itself
          (signature, description, parameters, examples) is generated by Sphinx
          from the object's docstring. We do the same: the object list, page
          title and section come from the pinned ``.rst`` files, the signature
          and docstring from the installed ``polars==2.0.0`` (the exact version
          the docs were built from). A page longer than ``API_SPLIT_TOKENS`` is
          split at numpydoc section boundaries (and, inside *Examples*, between
          doctest blocks), every part keeping the page title + signature header.

``guide`` The User Guide, the version upgrade guides (incl. the 1.x -> 2.0
          guide) and the hand-written prose of the reference pages, split by
          section headings into ~``GUIDE_MIN_TOKENS``-``GUIDE_MAX_TOKENS``-token
          chunks. ``{{code_block(...)}}`` macros are expanded to the Python
          snippet they embed, and a code block is never split.

Every chunk carries metadata: ``source`` (path inside the corpus), ``title``
(page title), ``section`` (heading path), and ``api_names`` (the
fully-qualified API names it documents, e.g. ``Expr.str.to_uppercase``, using
the reference's own naming relative to ``polars``).

Token counts use the generation model's tokenizer (``Qwen/Qwen3.5-4B`` at a
pinned revision), so the retrieval context budget is in the units the model
actually sees.

CLI::

    python -m polars_llm.rag.chunk            # -> data/rag/chunks.jsonl + stats
"""

