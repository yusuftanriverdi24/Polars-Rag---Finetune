def _expand_entries(entries: list[RstEntry]) -> list[RstEntry]:
    """Turn automodule/autoclass directives into concrete entries."""

    out: list[RstEntry] = []
    for e in entries:
        if e.directive == "automodule":
            mod = importlib.import_module(e.name)
            short = e.name.split(".")[-1]
            for member in sorted(getattr(mod, "__all__", [])):
                if callable(getattr(mod, member, None)):
                    out.append(RstEntry(f"{short}.{member}", "polars", "automodule", e.source, e.title, e.section))
        else:
            out.append(e)
    return out


def _resolve_entry(e: RstEntry):
    if e.directive == "automodule":
        mod_name, member = e.name.split(".", 1)
        return getattr(importlib.import_module(f"polars.{mod_name}"), member, None)
    return resolve_object(e.name, e.module)


def _api_display_name(e: RstEntry) -> str:
    # `.. autoclass:: Col` in `polars.functions.col` documents `pl.col`.
    if e.module == "polars.functions.col" and e.name == "Col":
        return "col"
    return e.name.lstrip("~")


def build_api_chunks(corpus: Path, count: TokenCounter) -> tuple[list[Chunk], list[RstPage], list[str]]:
    ref_dir = corpus / REFERENCE_DIR
    pages = [
        parse_rst_page(p, p.relative_to(corpus).as_posix())
        for p in sorted(ref_dir.rglob("*.rst"))
    ]
    chunks: list[Chunk] = []
    unresolved: list[str] = []
    seen: set[str] = set()
    for page in pages:
        for e in _expand_entries(page.entries):
            name = _api_display_name(e)
            if name in seen:  # e.g. listed on two pages
                continue
            raw = _resolve_entry(e)
            if raw is None:
                unresolved.append(f"{e.module}:{e.name}")
                continue
            seen.add(name)
            doc = _docstring(raw)
            if name == "col":  # `:members: __call__` -> include the call docs
                call_doc = inspect.getdoc(raw.__call__) or ""
                doc = f"{doc}\n\n{call_doc}".strip()
            signature = _signature(name, raw)
            header = f"polars.{name}\n{signature}" if not signature.startswith(name) else f"polars.{signature}"
            parts = split_api_doc(header, doc, count)
            for k, body in enumerate(parts):
                cid = f"api:{name}" + (f"#p{k + 1}" if len(parts) > 1 else "")
                chunks.append(
                    Chunk(
                        id=cid,
                        kind="api",
                        source=e.source,
                        title=f"polars.{name}",
                        section=" > ".join(x for x in (page.title, e.section) if x),
                        api_names=[name],
                        text=body,
                        n_tokens=count(body),
                        signature=signature,
                        part=k + 1,
                        n_parts=len(parts),
                        extra={"module": e.module, "directive": e.directive},
                    )
                )
    return chunks, pages, unresolved


# ---------------------------------------------------------------------------
# guide chunks (markdown user guide + upgrade guides + reference prose)
# ---------------------------------------------------------------------------

_CODE_BLOCK_MACRO = re.compile(
    r"\{\{\s*code_block\(\s*'([^']+)'\s*,\s*'([^']+)'\s*(?:,\s*\[([^\]]*)\])?[^}]*?\)\s*\}\}",
    re.DOTALL,
)
_OTHER_MACRO = re.compile(r"\{\{.*?\}\}", re.DOTALL)
_FENCE = re.compile(r"^\s*(`{3,}|~{3,})")
_MD_HEADING = re.compile(r"^(#{1,6})\s+(.+?)\s*#*\s*$")
_QUOTED = re.compile(r"'([^']+)'|\"([^\"]+)\"")


def _snippet(corpus: Path, rel_path: str, section: str) -> str | None:
    path = corpus / SNIPPET_DIR / f"{rel_path}.py"
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    m = re.search(
        rf"#\s*--8<--\s*\[start:{re.escape(section)}\]\n(.*?)#\s*--8<--\s*\[end:{re.escape(section)}\]",
        text,
        re.DOTALL,
    )
    return m.group(1).strip("\n") if m else None


def load_api_links(corpus: Path) -> dict[str, str]:
    """Short name -> fully-qualified python API name, from API_REFERENCE_LINKS.yml."""

    import yaml

    path = corpus / API_LINKS_FILE
    if not path.exists():
        return {}
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    out: dict[str, str] = {}
    for short, value in (data.get("python") or {}).items():
        link = value.get("link") if isinstance(value, dict) else value
        if not isinstance(link, str):
            continue
        m = re.search(r"#(polars\.[\w.]+)$", link) or re.search(r"/(polars\.[\w.]+)\.html", link)
        out[str(short)] = m.group(1) if m else str(short)
    return out


def expand_markdown(text: str, corpus: Path, links: dict[str, str]) -> tuple[str, list[str]]:
    """Expand ``{{code_block(...)}}`` macros to their Python snippets and drop
    mkdocs-only syntax. Returns (markdown, raw API link names it referenced)."""

    referenced: list[str] = []

    def repl(m: re.Match) -> str:
        path, section, link_list = m.group(1), m.group(2), m.group(3) or ""
        for q in _QUOTED.finditer(link_list):
            short = q.group(1) or q.group(2)
            referenced.append(links.get(short, short))
        code = _snippet(corpus, path, section)
        return f"\n```python\n{code}\n```\n" if code else ""

    text = _CODE_BLOCK_MACRO.sub(repl, text)
    text = _OTHER_MACRO.sub("", text)
    # Drop executed-output fences that only include a snippet (`--8<-- "..."`).
    text = re.sub(r"^\s*```[^\n]*exec=\"on\"[^\n]*\n(?:[^\n]*--8<--[^\n]*\n)+\s*```[^\n]*$", "", text, flags=re.MULTILINE)
    text = re.sub(r"^[^\n]*--8<--[^\n]*$", "", text, flags=re.MULTILINE)
    return text, referenced


def markdown_blocks(text: str) -> tuple[str, list[tuple[str, str]]]:
    """Split markdown into (section path, block) pairs; a fenced code block is
    always one block. Returns (page title, blocks)."""

    title = ""
    stack: list[tuple[int, str]] = []
    blocks: list[tuple[str, str]] = []
    buf: list[str] = []
    in_fence: str | None = None

    def section() -> str:
        return " > ".join(t for _, t in stack)

    def flush() -> None:
        s = "\n".join(buf).strip("\n")
        if s.strip() and not _is_empty_block(s):
            blocks.append((section(), s))
        buf.clear()

    for line in text.splitlines():
        fence = _FENCE.match(line)
        if in_fence:
            buf.append(line)
            if fence and fence.group(1)[0] == in_fence[0] and len(fence.group(1)) >= len(in_fence):
                in_fence = None
                flush()
            continue
        if fence:
            flush()
            in_fence = fence.group(1)
            buf.append(line)
            continue
        h = _MD_HEADING.match(line)
        if h:
            flush()
            level, heading = len(h.group(1)), h.group(2).strip()
            if level == 1 and not title:
                title = heading
                stack = []
                continue
            while stack and stack[-1][0] >= level:
                stack.pop()
            stack.append((level, heading))
            blocks.append((section(), f"{h.group(1)} {heading}"))
            continue
        if not line.strip():
            flush()
            continue
        buf.append(line)
    flush()
    return title, blocks


GUIDE_TINY_TOKENS = 60  # smaller chunks are merged into a neighbour


def _is_empty_block(block: str) -> bool:
    """An empty code fence or a bare HTML comment carries no content."""

    s = block.strip()
    if re.fullmatch(r"<!--.*?-->", s, re.DOTALL):
        return True
    lines = s.splitlines()
    return bool(_FENCE.match(lines[0])) and all(
        not ln.strip() or _FENCE.match(ln) for ln in lines
    )


def _is_code_block(block: str) -> bool:
    return bool(_FENCE.match(block.lstrip("\n").splitlines()[0]))


def _split_oversized_text_block(block: str, count: TokenCounter) -> list[str]:
    """Split a non-code block (long list / table) above GUIDE_MAX by lines; a
    markdown table repeats its header row in every piece."""

    lines = block.splitlines()
    header: list[str] = []
    if len(lines) > 2 and lines[0].lstrip().startswith("|") and re.match(r"^\s*\|[\s:|-]+\|\s*$", lines[1]):
        header, lines = lines[:2], lines[2:]
    budget = GUIDE_MAX_TOKENS - count("\n".join(header))
    return ["\n".join(header + g.split("\n")) for g in _pack(lines, budget, count, sep="\n")]


def pack_guide_blocks(
    blocks: list[tuple[str, str]], count: TokenCounter
) -> list[tuple[str, str]]:
    """Pack (section, block) pairs into ~GUIDE_MIN..GUIDE_MAX-token chunks.

    A chunk is closed when the next block would push it past GUIDE_MAX, or when
    a new section starts and the chunk already holds GUIDE_MIN tokens. A code
    block is never split (an oversized one is its own chunk); an oversized
    prose block (long list / table) is split by lines. Chunks smaller than
    GUIDE_TINY_TOKENS are merged into the previous chunk (or the next one).
    """

    expanded: list[tuple[str, str]] = []
    for sec, block in blocks:
        if not _is_code_block(block) and count(block) > GUIDE_MAX_TOKENS:
            expanded.extend((sec, piece) for piece in _split_oversized_text_block(block, count))
        else:
            expanded.append((sec, block))

    out: list[tuple[str, str]] = []
    cur: list[str] = []
    cur_section = ""
    cur_tokens = 0
    for sec, block in expanded:
        t = count(block)
        new_section = cur and sec != cur_section and not sec.startswith(cur_section + " > ")
        if cur and (cur_tokens + t > GUIDE_MAX_TOKENS or (new_section and cur_tokens >= GUIDE_MIN_TOKENS)):
            out.append((cur_section, "\n\n".join(cur)))
            cur, cur_tokens = [], 0
        if not cur:
            cur_section = sec
        cur.append(block)
        cur_tokens += t
    if cur:
        out.append((cur_section, "\n\n".join(cur)))
    return _merge_tiny(out, count)


def _merge_tiny(chunks: list[tuple[str, str]], count: TokenCounter) -> list[tuple[str, str]]:
    merged: list[tuple[str, str]] = []
    pending: tuple[str, str] | None = None  # a tiny leading chunk awaiting a successor
    for sec, text in chunks:
        if pending is not None:  # the merged chunk starts where the tiny one did
            sec, text = pending[0], f"{pending[1]}\n\n{text}"
            pending = None
        if count(text) < GUIDE_TINY_TOKENS:
            if merged:
                psec, ptext = merged[-1]
                merged[-1] = (psec, f"{ptext}\n\n{text}")
            else:
                pending = (sec, text)
            continue
        merged.append((sec, text))
    if pending is not None:
        merged.append(pending)
    return merged


def _guide_api_names(text: str, referenced: Iterable[str], known: set[str]) -> list[str]:
    names = set()
    for raw in referenced:
        c = canonical_api_name(raw, known)
        if c:
            names.add(c)
    for m in _ROLE.finditer(text):  # rst roles left in prose
        c = canonical_api_name(m.group(2) or m.group(1), known)
        if c:
            names.add(c)
    for m in re.finditer(r"\bpl\.([a-z_][a-z0-9_]*)\(", text):  # top-level functions in code
        if m.group(1) in known:
            names.add(m.group(1))
    return sorted(names)


def build_guide_chunks(
    corpus: Path, count: TokenCounter, known: set[str], rst_pages: list[RstPage]
) -> list[Chunk]:
    links = load_api_links(corpus)
    chunks: list[Chunk] = []
    paths: list[Path] = []
    for d in GUIDE_DIRS:
        paths.extend(sorted((corpus / d).rglob("*.md")))
    for path in paths:
        rel = path.relative_to(corpus).as_posix()
        if rel.endswith("upgrade/index.md"):
            continue
        raw = path.read_text(encoding="utf-8")
        # Expand macros per page, then attribute each referenced link to the
        # chunk containing the expanded snippet via a marker comment.
        expanded, _ = _expand_with_markers(raw, corpus, links)
        title, blocks = markdown_blocks(expanded)
        title = title or path.stem
        for k, (sec, text) in enumerate(pack_guide_blocks(blocks, count)):
            text, refs = _strip_markers(text)
            chunks.append(
                Chunk(
                    id=f"guide:{rel}#{k + 1:03d}",
                    kind="guide",
                    source=rel,
                    title=title,
                    section=sec,
                    api_names=_guide_api_names(text, refs, known),
                    text=text,
                    n_tokens=count(text),
                )
            )
    # Hand-written prose on the API reference pages (intros, usage examples).
    for page in rst_pages:
        if not page.prose_blocks or sum(count(b) for _, b in page.prose_blocks) < 40:
            continue
        for k, (sec, text) in enumerate(pack_guide_blocks(page.prose_blocks, count)):
            chunks.append(
                Chunk(
                    id=f"guide:{page.source}#{k + 1:03d}",
                    kind="guide",
                    source=page.source,
                    title=page.title,
                    section=sec,
                    api_names=_guide_api_names(text, [], known),
                    text=text,
                    n_tokens=count(text),
                )
            )
    return chunks


_MARKER = "<!--api:{}-->"
_MARKER_RE = re.compile(r"<!--api:([^>]*)-->\n?")


def _expand_with_markers(text: str, corpus: Path, links: dict[str, str]) -> tuple[str, list[str]]:
    """Like expand_markdown, but leaves a marker naming the referenced APIs at
    the top of each expanded code block, so they stay with the chunk that ends
    up containing that code (``_strip_markers`` removes them again)."""

    def repl(m: re.Match) -> str:
        path, section, link_list = m.group(1), m.group(2), m.group(3) or ""
        refs = [links.get(q.group(1) or q.group(2), q.group(1) or q.group(2)) for q in _QUOTED.finditer(link_list)]
        code = _snippet(corpus, path, section)
        if not code:
            return ""
        marker = _MARKER.format(",".join(refs))
        return f"\n```python\n{marker}\n{code}\n```\n"

    text = _CODE_BLOCK_MACRO.sub(repl, text)
    text, _ = expand_markdown(text, corpus, links)  # strip remaining macros / includes
    return text, []


def _strip_markers(text: str) -> tuple[str, list[str]]:
    refs: list[str] = []
    for m in _MARKER_RE.finditer(text):
        refs.extend(r for r in m.group(1).split(",") if r)
    return _MARKER_RE.sub("", text), refs


