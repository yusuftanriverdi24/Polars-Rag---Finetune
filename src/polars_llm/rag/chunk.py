_NAME_PREFERENCE = ("Expr.", "DataFrame.", "LazyFrame.", "", "GroupBy.", "LazyGroupBy.", "Series.")


def _preference(name: str) -> tuple[int, str]:
    for i, prefix in enumerate(_NAME_PREFERENCE):
        if prefix == "" and "." not in name:
            return (i, name)
        if prefix and name.startswith(prefix):
            return (i, name)
    return (len(_NAME_PREFERENCE), name)


def canonical_api_name(raw: str, known: set[str]) -> str | None:
    """Map a raw reference (``polars.Expr.alias``, ``pl.col``, ``str.len_bytes``,
    ``polars.dataframe.group_by.GroupBy.agg``) onto a documented API name."""

    name = raw.strip().lstrip("~").strip()
    name = re.sub(r"\(\)$", "", name)
    for prefix in ("polars.", "pl."):
        if name.startswith(prefix):
            name = name[len(prefix) :]
    if name.startswith("cs."):
        name = "selectors." + name[3:]
    if name in known:
        return name
    parts = name.split(".")
    for i in range(1, len(parts)):  # drop leading module components
        candidate = ".".join(parts[i:])
        if candidate in known:
            return candidate
    suffix = "." + name
    matches = sorted((k for k in known if k.endswith(suffix)), key=_preference)
    return matches[0] if matches else None


# ---------------------------------------------------------------------------
# reference .rst parsing
# ---------------------------------------------------------------------------

_RST_UNDERLINE = re.compile(r"^([=\-~^\"'`#*+])\1{2,}\s*$")
_DIRECTIVE = re.compile(r"^(\s*)\.\.\s+([\w:-]+)::\s*(.*)$")
_ROLE = re.compile(r":(?:meth|func|class|attr|mod|obj):`~?([^`<]+?)(?:\s*<([^>]+)>)?`")


@dataclass
class RstEntry:
    name: str  # as written, relative to `module`
    module: str
    directive: str  # autosummary | autoclass | autoproperty | automethod | automodule | autofunction
    source: str
    title: str
    section: str
    options: list[str] = field(default_factory=list)


@dataclass
class RstPage:
    source: str
    title: str
    entries: list[RstEntry]
    prose_blocks: list[tuple[str, str]]  # (section path, markdown-ish block)


def _rst_headings(lines: list[str]) -> dict[int, str]:
    """Map line index of a heading's text -> heading text (over/underline styles)."""

    heads: dict[int, str] = {}
    for i, line in enumerate(lines):
        if i + 1 < len(lines) and line.strip() and _RST_UNDERLINE.match(lines[i + 1]):
            if not _RST_UNDERLINE.match(line) and len(lines[i + 1].strip()) >= len(line.strip()) - 1:
                heads[i] = line.strip()
    return heads


def parse_rst_page(path: Path, rel: str) -> RstPage:
    lines = path.read_text(encoding="utf-8").splitlines()
    heads = _rst_headings(lines)
    title = next(iter(heads.values()), path.stem)
    module = "polars"
    section_stack: list[str] = []
    entries: list[RstEntry] = []
    prose: list[tuple[str, str]] = []
    para: list[str] = []

    def section() -> str:
        return " > ".join(section_stack)

    def flush_para() -> None:
        text = "\n".join(para).strip()
        if text:
            prose.append((section(), text))
        para.clear()

    i = 0
    while i < len(lines):
        line = lines[i]
        if i in heads:
            flush_para()
            text = heads[i]
            if text != title:
                section_stack[:] = [text]
            i += 2
            continue
        if _RST_UNDERLINE.match(line):  # overline
            i += 1
            continue
        m = _DIRECTIVE.match(line)
        if m:
            flush_para()
            indent, directive, arg = len(m.group(1)), m.group(2), m.group(3).strip()
            body: list[str] = []
            j = i + 1
            while j < len(lines) and (not lines[j].strip() or len(lines[j]) - len(lines[j].lstrip()) > indent):
                body.append(lines[j])
                j += 1
            if directive == "currentmodule":
                module = arg
            elif directive == "autosummary":
                for b in body:
                    s = b.strip()
                    if s and not s.startswith(":"):
                        entries.append(RstEntry(s, module, "autosummary", rel, title, section()))
            elif directive in {"autoclass", "autoproperty", "automethod", "autofunction", "automodule"}:
                opts = [b.strip() for b in body if b.strip().startswith(":")]
                entries.append(RstEntry(arg, module, directive, rel, title, section(), opts))
            elif directive in {"code-block", "code"}:
                code = "\n".join(body).strip("\n")
                prose.append((section(), f"```{arg or 'python'}\n{_dedent(code)}\n```"))
            elif directive in {"note", "warning", "tip", "seealso", "admonition", "versionchanged"}:
                text = _dedent("\n".join(b for b in body if not b.strip().startswith(":"))).strip()
                if text:
                    prose.append((section(), _rst_inline(text)))
            # toctree / grid / raw / table / topic: navigation or layout -> dropped
            i = j
            continue
        if line.strip():
            para.append(_rst_inline(line.strip()))
        else:
            flush_para()
        i += 1
    flush_para()
    return RstPage(rel, title, entries, prose)


def _dedent(text: str) -> str:
    import textwrap

    return textwrap.dedent(text)


def _rst_inline(text: str) -> str:
    text = _ROLE.sub(lambda m: f"`{(m.group(2) or m.group(1)).strip()}`", text)
    return text.replace("``", "`")


# ---------------------------------------------------------------------------
# resolving documented objects in the installed polars
# ---------------------------------------------------------------------------


def _root_instances() -> dict:
    """Instances used to reach namespace classes behind properties (``Expr.str``)."""

    import polars as pl

    return {
        pl.Expr: pl.col("a"),
        pl.Series: pl.Series("a", [1]),
        pl.DataFrame: pl.DataFrame({"a": [1]}),
        pl.LazyFrame: pl.LazyFrame({"a": [1]}),
        pl.DataTypeExpr: pl.dtype_of("a"),
    }


def resolve_object(name: str, module: str):
    """Return the raw documented object (function / property / class) or None."""

    name = name.lstrip("~")
    try:
        obj = importlib.import_module(module)
    except ImportError:
        return None
    parts = name.split(".")
    instances = _root_instances()
    try:
        for p in parts[:-1]:
            if inspect.ismodule(obj) and not hasattr(obj, p):
                # Submodule not imported by its parent (e.g. polars.testing).
                try:
                    obj = importlib.import_module(f"{obj.__name__}.{p}")
                    continue
                except ImportError:
                    return None
            if inspect.isclass(obj):
                static = inspect.getattr_static(obj, p)
                if isinstance(static, property):
                    inst = instances.get(obj)
                    if inst is None:
                        return None
                    obj = type(getattr(inst, p))  # namespace class, e.g. ExprStringNameSpace
                    continue
            obj = getattr(obj, p)
        last = parts[-1]
        raw = inspect.getattr_static(obj, last) if inspect.isclass(obj) else getattr(obj, last)
    except AttributeError:
        return None
    if isinstance(raw, (staticmethod, classmethod)):
        raw = raw.__func__
    return raw


def _signature(name: str, raw) -> str:
    target = raw.fget if isinstance(raw, property) else raw
    if isinstance(raw, property):
        return f"{name}  (property)"
    try:
        if inspect.isclass(target):
            return f"class {name}{inspect.signature(target)}"
        return f"{name}{inspect.signature(target)}"
    except (TypeError, ValueError):
        return name


def _docstring(raw) -> str:
    target = raw.fget if isinstance(raw, property) else raw
    return inspect.getdoc(target) or ""


# ---------------------------------------------------------------------------
# splitting helpers
# ---------------------------------------------------------------------------

_NUMPYDOC_HEADER = re.compile(r"^([A-Z][A-Za-z ]+)\n-{3,}[ \t]*$", re.MULTILINE)


def _numpydoc_sections(doc: str) -> list[str]:
    """Split a numpydoc docstring into [summary, 'Parameters\\n---...', ...]."""

    starts = [m.start() for m in _NUMPYDOC_HEADER.finditer(doc)]
    if not starts:
        return [doc]
    bounds = [0, *starts, len(doc)]
    return [doc[a:b].strip("\n") for a, b in zip(bounds, bounds[1:]) if doc[a:b].strip()]


def _paragraphs(text: str) -> list[str]:
    return [p for p in re.split(r"\n\s*\n", text) if p.strip()]


def _pack(pieces: list[str], limit: int, count: TokenCounter, sep: str = "\n\n") -> list[str]:
    """Greedily pack pieces into groups of at most ``limit`` tokens (a single
    oversized piece forms its own group; pieces are never cut)."""

    groups: list[str] = []
    cur: list[str] = []
    cur_tokens = 0
    for piece in pieces:
        t = count(piece)
        if cur and cur_tokens + t > limit:
            groups.append(sep.join(cur))
            cur, cur_tokens = [], 0
        cur.append(piece)
        cur_tokens += t
    if cur:
        groups.append(sep.join(cur))
    return groups


def _doctest_statements(para: str) -> list[str]:
    """Split a doctest block at statement boundaries: a ``>>>`` line that
    follows output (not a ``>>>``/``...`` line) starts a new statement."""

    out: list[list[str]] = []
    prev_is_input = False
    for line in para.splitlines():
        is_prompt = line.startswith(">>>")
        if is_prompt and not prev_is_input and out:
            out.append([line])
        elif not out:
            out.append([line])
        else:
            out[-1].append(line)
        prev_is_input = is_prompt or line.startswith("...")
    return ["\n".join(s) for s in out]


def split_api_doc(header: str, doc: str, count: TokenCounter) -> list[str]:
    """Body parts for an API page: whole if short, else split at numpydoc
    sections (Examples further split between doctest blocks, and a single
    oversized doctest block between its statements)."""

    whole = f"{header}\n\n{doc}".strip()
    if count(whole) <= API_SPLIT_TOKENS:
        return [whole]
    budget = API_PART_TOKENS - count(header)
    pieces: list[str] = []
    for sec in _numpydoc_sections(doc):
        if count(sec) <= budget:
            pieces.append(sec)
            continue
        paras: list[str] = []
        for p in _paragraphs(sec):
            if count(p) > budget and p.lstrip().startswith(">>>"):
                paras.extend(_pack(_doctest_statements(p), budget, count, sep="\n"))
            else:
                paras.append(p)
        pieces.extend(_pack(paras, budget, count))
    return [f"{header}\n\n{body}".strip() for body in _pack(pieces, budget, count)]


