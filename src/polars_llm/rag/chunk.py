def load_token_counter(model_id: str = TOKENIZER_ID, revision: str = TOKENIZER_REVISION) -> TokenCounter:
    """Token counter backed by the generation model's tokenizer (pinned revision)."""

    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained(model_id, revision=revision)
    tok = getattr(tok, "tokenizer", tok)  # multimodal processor -> text tokenizer

    def count(text: str) -> int:
        return len(tok(text, add_special_tokens=False)["input_ids"])

    return count


def whitespace_token_counter(text: str) -> int:
    """Crude counter for tests (no tokenizer download)."""

    return len(text.split())


