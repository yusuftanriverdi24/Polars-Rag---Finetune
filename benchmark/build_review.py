"""Generate benchmark/REVIEW.md: a spot-check table of every task.

Reads the per-category task sources (via build_tasks.collect_source_tasks) so it
can include the authoring-only `touches_2_0_change` flag, and writes a Markdown
table of (id, difficulty, category, one-line instruction, touches 2.0 change).

Usage::

    python benchmark/build_review.py
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))

from build_tasks import CATEGORY_ORDER, collect_source_tasks  # noqa: E402


def _one_line(text: str) -> str:
    """Collapse an instruction to a single table-safe line."""

    line = " ".join(text.split())
    return line.replace("|", "\\|")


def build(out_path: Path) -> None:
    tasks = collect_source_tasks()

    by_diff = Counter(t["difficulty"] for t in tasks)
    by_cat = Counter(t["category"] for t in tasks)
    touches = sum(1 for t in tasks if t["touches_2_0_change"])
    n = len(tasks)

    diff_rank = {"easy": 0, "medium": 1, "hard": 2}
    cat_rank = {c: i for i, c in enumerate(CATEGORY_ORDER)}
    ordered = sorted(tasks, key=lambda t: (cat_rank.get(t["category"], 99), diff_rank.get(t["difficulty"], 9), t["id"]))

    lines = [
        "# Benchmark task review",
        "",
        f"{n} tasks for spot-checking. Generated by `benchmark/build_review.py` "
        "from the per-category sources in `benchmark/tasks_src/`.",
        "",
        f"- **By difficulty:** "
        + ", ".join(f"{k} {by_diff[k]}" for k in ("easy", "medium", "hard")),
        f"- **By category:** " + ", ".join(f"{c} {by_cat[c]}" for c in CATEGORY_ORDER),
        f"- **Touches a 2.0 change / pandas trap:** {touches} / {n} "
        f"({touches / n:.0%})",
        "",
        "Expected outputs are computed by running each reference solution under "
        "Polars 2.0.0; every reference passes `validate_tasks` (no errors, no "
        "deprecation warnings) and the reference smoke test.",
        "",
        "| id | diff | category | instruction | 2.0 |",
        "|----|------|----------|-------------|:---:|",
    ]
    for t in ordered:
        mark = "✅" if t["touches_2_0_change"] else ""
        lines.append(
            f"| `{t['id']}` | {t['difficulty']} | {t['category']} | "
            f"{_one_line(t['instruction'])} | {mark} |"
        )
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote review table for {n} tasks to {out_path}")


if __name__ == "__main__":
    build(HERE / "REVIEW.md")
